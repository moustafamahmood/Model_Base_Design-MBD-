num =input('Enter numbers :\n') ;
maxvalue = max(num);
disp(['Maximum Value: ', num2str(maxvalue)]);

minvalue = min(num);
disp(['Minimum  Value: ', num2str(minvalue)]);

totalsum = sum(num);
disp(['Sum of Elements: ', num2str(totalsum)]);

meanvalue = mean(num);
disp(['Mean Value: ', num2str(meanvalue)])

disp('Original Vector:');
disp(num);
